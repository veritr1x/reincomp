"""Package a tested native Linux runtime for the Bunker web builder on Linux."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile

from stage import FIREBASE_LINUX_SHA256, GRPC_LINUX_SHA256, UNITY_FILES

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def package(args):
    version = (ROOT / "launcher/VERSION").read_text().strip()
    lock = json.loads((ROOT / "bunker.lock.json").read_bytes())["bunker"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Expected a release version")
    data = "Reincarnation_Data/"
    # Explicit distribution inputs. Everything else in a stage derives from the user's APK.
    members = {
        "GameAssembly.so": args.assembly_sha256,
        "Reincarnation.x86_64": UNITY_FILES["LinuxPlayer"],
        "UnityPlayer.so": UNITY_FILES["UnityPlayer.so"],
        data + "Resources/unity default resources": UNITY_FILES["Data/Resources/unity default resources"],
        data + "Native/libgrpc_csharp_ext.x64.so": GRPC_LINUX_SHA256,
        data + "Native/FirebaseCppApp-9_6_0.so": FIREBASE_LINUX_SHA256,
        "bunker-server": lock["server"]["linux-x86_64"]["sha256"],
    }
    args.out.mkdir(parents=True, exist_ok=True)
    name = f"reincomp-linux-x86_64-{version}.tar.gz"
    target = args.out / name
    with tempfile.TemporaryDirectory(dir=args.out) as tmp:
        work = Path(tmp)
        runtime = work / "runtime"
        for name_in_kit, expected in members.items():
            src = args.server if name_in_kit == "bunker-server" else args.stage / name_in_kit
            if digest(src) != expected:
                raise ValueError(f"Unexpected release input: {src}")
            dest = runtime / name_in_kit
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
            dest.chmod(0o755 if name_in_kit in ("bunker-server", "Reincarnation.x86_64") else 0o644)
        for sdk in ("firebase", "grpc"):
            shutil.copytree(args.stage / "licenses" / sdk, runtime / "licenses" / sdk)
        for notice in ("LICENSE", "THIRD-PARTY.md"):
            shutil.copyfile(ROOT / notice, runtime / "licenses" / notice)
        for src, notice_name in ((args.bunker / "LICENSE", "Bunker-LICENSE"),
                          (args.bunker / "upstream/lunar-tear/LICENSE", "Lunar-Tear-LICENSE"),
                          (args.remill_license, "Remill-LICENSE")):
            shutil.copyfile(src, runtime / "licenses" / notice_name)
        scripts = runtime / "tools"
        scripts.mkdir()
        for src in (HERE / "web_launch.py", HERE / "bundle_worker.py",
                    *(HERE.parent / "native_player" / f for f in ("package_assets.py", "desktop_bundles.py", "desktop_shader.py"))):
            shutil.copyfile(src, scripts / src.name)

        # Use an unpacked python-build-standalone install_only distribution. Install the
        # converter into a clean prefix using the release wheels, never a user's environment.
        python = args.python_prefix / "bin/python3.12"
        if subprocess.check_output([python, "-IS", "-c", "import sys;print(sys.version.split()[0])"], text=True).strip() != "3.12.14":
            raise ValueError("Expected python-build-standalone CPython 3.12.14")
        prefix = runtime / "python"
        (prefix / "bin").mkdir(parents=True)
        shutil.copy2(python.resolve(), prefix / "bin/python3")
        lib = prefix / "lib/python3.12"
        shutil.copytree(args.python_prefix / "lib/python3.12", lib,
                        ignore=shutil.ignore_patterns("site-packages", "__pycache__", "*.pyc", "test", "tests"))
        shutil.copy2(args.python_prefix / "lib/libpython3.12.so.1.0", prefix / "lib")
        subprocess.run([python, "-Im", "pip", "install", "--no-index", "--only-binary=:all:",
                        "--find-links", str(args.wheels), "--no-compile", "--target", str(lib / "site-packages"),
                        "-r", str(HERE / "converter-requirements.txt")], check=True)
        # Console entry points generated by pip refer to the build host's Python.
        # The converter imports the modules directly.
        entrypoints = lib / "site-packages/bin"
        if entrypoints.is_dir():
            shutil.rmtree(entrypoints)
        subprocess.run([prefix / "bin/python3", "-IB", "-c", "import UnityPy, texture2ddecoder, lz4.block"], check=True)
        packed = work / "download"
        with packed.open("wb") as dest, gzip.GzipFile(filename="", fileobj=dest, mode="wb", mtime=0, compresslevel=5) as gz, tarfile.open(fileobj=gz, mode="w|") as tar:
            for path in sorted(runtime.rglob("*")):
                if path.is_dir():
                    continue
                rel = path.relative_to(runtime).as_posix()
                info = tarfile.TarInfo(rel)
                info.size = path.stat().st_size
                info.mode = 0o755 if path.stat().st_mode & 0o111 else 0o644
                with path.open("rb") as src:
                    tar.addfile(info, src)
        pin = dict(reincompVersion=version, bunkerVersion=lock["release"].removeprefix("v"),
                   asset=name, sha256=digest(packed), size=packed.stat().st_size)
        packed.replace(target)
        (args.out / "linux-release.json").write_text(json.dumps(pin, indent=2) + "\n")
        print(json.dumps(pin), flush=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    for key in ("stage", "server", "python-prefix", "wheels", "bunker", "remill-license", "out"):
        p.add_argument("--" + key, type=Path, required=True)
    p.add_argument("--assembly-sha256", required=True, help="SHA-256 of the gameplay-tested GameAssembly.so")
    package(p.parse_args())
